def test_pre_push_fallback_checks_current_branch_and_unpushed_commits(
    guard_path: Path, git_repo: Path
) -> None:
    clean = _run_guard(guard_path, ["pre-push"], cwd=git_repo)
    _git(git_repo, "checkout", "-q", "-b", GOLDEN["ref_deny"][0])

    flagged = _run_guard(guard_path, ["pre-push"], cwd=git_repo)

    assert clean.returncode == 0, clean.stderr
    assert flagged.returncode == 1
    assert "current branch" in flagged.stderr


def test_push_mode_audits_only_the_pushed_range(guard_path: Path, git_repo: Path) -> None:
    """Commits already on the branch before the push are not re-judged."""
    _commit(git_repo, GOLDEN["msg_deny"][7])
    before = _commit(git_repo, "chore: clean base")
    clean_after = _commit(git_repo, GOLDEN["msg_allow"][7])
    clean = _run_guard(
        guard_path, ["push", "--before", before, "--after", clean_after], cwd=git_repo
    )
    dirty_after = _commit(git_repo, DENIED_MESSAGE)

    dirty = _run_guard(
        guard_path, ["push", "--before", clean_after, "--after", dirty_after], cwd=git_repo
    )

    assert clean.returncode == 0, clean.stderr
    assert dirty.returncode == 1
    assert f"commit {dirty_after[:12]} message" in dirty.stderr


type _Routes = dict[str, object]


@pytest.fixture
def api_server() -> Iterator[Callable[[_Routes], str]]:
    """Serves canned GitHub API JSON keyed by request path plus query."""
    servers: list[ThreadingHTTPServer] = []

    def _start(routes: _Routes) -> str:
        class _Handler(BaseHTTPRequestHandler):
            def do_GET(self) -> None:
                parts = urlsplit(self.path)
                key = f"{parts.path}?{parts.query}" if parts.query else parts.path
                if key not in routes:
                    self.send_error(404)
                    return
                payload = json.dumps(routes[key]).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)

            def log_message(self, format: str, *args: object) -> None:
                return

        server = ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
        servers.append(server)
        threading.Thread(target=server.serve_forever, daemon=True).start()
        return f"http://127.0.0.1:{server.server_address[1]}"

    yield _start
    for server in servers:
        server.shutdown()
        server.server_close()


def _api_commit(index: int, message: str = "fix: clean", email: str = CLEAN_EMAIL) -> object:
    return {
        "sha": f"{index:040x}",
        "commit": {
            "message": message,
            "author": {"email": email},
            "committer": {"email": CLEAN_EMAIL},
        },
    }


def _pull_routes(
    *,
    title: str = "ci: add guard",
    body: str | None = "Plain description.",
    head_ref: str = "ci/guard",
    labels: Sequence[str] = ("dependencies",),
    commits: Sequence[object] = (),
    reported_commits: int | None = None,
) -> _Routes:
    base = "/repos/acme/widgets/pulls/7"
    pages = [list(commits[start : start + 100]) for start in range(0, len(commits), 100)] or [[]]
    routes: _Routes = {
        base: {
            "title": title,
            "body": body,
            "head": {"ref": head_ref},
            "labels": [{"name": label} for label in labels],
            "commits": len(commits) if reported_commits is None else reported_commits,
        }
    }
    for page_number, page in enumerate(pages, start=1):
        routes[f"{base}/commits?per_page=100&page={page_number}"] = page
    if len(pages[-1]) == 100:
        routes[f"{base}/commits?per_page=100&page={len(pages) + 1}"] = []
    return routes


def _run_pull_request(
    guard_path: Path, api_url: str, cwd: Path
) -> subprocess.CompletedProcess[str]:
    return _run_guard(
        guard_path,
        ["pull-request", "--repo", "acme/widgets", "--number", "7"],
        cwd=cwd,
        env={"GITHUB_API_URL": api_url, "GITHUB_TOKEN": "test-token"},
    )


def test_pull_request_mode_paginates_and_passes_clean_metadata(
    guard_path: Path, tmp_path: Path, api_server: Callable[[_Routes], str]
) -> None:
    commits = [_api_commit(index) for index in range(150)]
    api_url = api_server(_pull_routes(body=None, commits=commits))

    completed = _run_pull_request(guard_path, api_url, tmp_path)

    assert completed.returncode == 0, completed.stderr
    assert "(150 commits): clean" in completed.stdout


def test_pull_request_mode_reports_every_offending_field(
    guard_path: Path, tmp_path: Path, api_server: Callable[[_Routes], str]
) -> None:
    routes = _pull_routes(
        title=GOLDEN["msg_deny"][4],
        body=GOLDEN["msg_deny"][5],
        head_ref=GOLDEN["ref_deny"][0],
        labels=("dependencies", LABEL_DENY[0]),
        commits=[_api_commit(1, message=DENIED_MESSAGE, email=GOLDEN["email_deny"][0])],
    )

    completed = _run_pull_request(guard_path, api_server(routes), tmp_path)

    assert completed.returncode == 1
    for field in (
        "pull request title",
        "pull request body",
        "head ref",
        f"label {LABEL_DENY[0]!r}",
        "message: matched",
        "author email: matched",
    ):
        assert field in completed.stderr


def test_pull_request_mode_fails_closed_on_incomplete_commit_listing(
    guard_path: Path, tmp_path: Path, api_server: Callable[[_Routes], str]
) -> None:
    routes = _pull_routes(commits=[_api_commit(1)], reported_commits=300)

    completed = _run_pull_request(guard_path, api_server(routes), tmp_path)

    assert completed.returncode == 2
    assert "Fetched 1 of 300" in completed.stderr


