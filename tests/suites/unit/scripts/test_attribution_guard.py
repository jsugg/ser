class _Guard(Protocol):
    REF_NAME: str
    COMMIT_MESSAGE: str
    EMAIL: str
    LABEL: str
    REF_RE: re.Pattern[str]
    MSG_RE: re.Pattern[str]
    EMAIL_RE: re.Pattern[str]
    LABEL_RE: re.Pattern[str]

    def strip_commit_message_comments(self, text: str) -> str: ...


@pytest.fixture(scope="module")
def guard_path(repo_root: Path) -> Path:
    """Returns the guard helper path inside the repository under test."""
    return repo_root / "scripts" / "attribution_guard.py"


@pytest.fixture(scope="module")
def guard(guard_path: Path) -> Iterator[_Guard]:
    """Loads the helper as a module; dataclasses need it registered in `sys.modules`."""
    spec = importlib.util.spec_from_file_location("attribution_guard_under_test", guard_path)
    assert spec is not None and spec.loader is not None
    module: ModuleType = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    try:
        spec.loader.exec_module(module)
        yield cast(_Guard, module)
    finally:
        sys.modules.pop(spec.name, None)


def test_vendored_patterns_match_shared_source(guard: _Guard) -> None:
    """The pattern strings must stay byte-identical to the shared source."""
    joined = "\0".join((guard.REF_NAME, guard.COMMIT_MESSAGE, guard.EMAIL, guard.LABEL))
    assert hashlib.sha256(joined.encode("utf-8")).hexdigest() == SHARED_PATTERN_DIGEST


